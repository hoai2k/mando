/**
 * Remove arm influence from Maul and Revan's lower garment shells.
 *
 * Their hands rest near the cloth at bind pose, so automatic weights attach
 * parts of the skirt/coat to the hands and forearms. Select whole connected
 * lower-body shells, leaving nearby sleeves and hands untouched. The game
 * applies the fix at load; the source GLBs remain unchanged.
 *
 * Usage: node tools/fix-sith-skirts.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { readGlb } from './lib/glb.mjs';

const models = [
  { id: 'maul', heightM: 1.88, expectedShells: [440] },
  { id: 'revan', heightM: 1.95, expectedShells: [2376, 1195, 223] },
];
const isArm = (name) => /^(upper_arm|forearm|hand)\./.test(name);

function connectedShells(prim) {
  // The GLBs split vertices along UV seams; weld equal positions before
  // walking triangle edges, as in the skin audit.
  const points = new Map();
  const pointOf = new Int32Array(prim.count);
  const parent = [];
  const find = (start) => {
    let p = start;
    while (parent[p] !== p) { parent[p] = parent[parent[p]]; p = parent[p]; }
    return p;
  };
  for (let v = 0; v < prim.count; v++) {
    const key = [0, 1, 2].map((axis) => Math.round(prim.positions[v * 3 + axis] * 1e4)).join(',');
    let p = points.get(key);
    if (p === undefined) { p = parent.length; parent.push(p); points.set(key, p); }
    pointOf[v] = p;
  }
  for (let i = 0; i < prim.indices.length; i += 3) {
    const a = find(pointOf[prim.indices[i]]);
    parent[find(pointOf[prim.indices[i + 1]])] = a;
    parent[find(pointOf[prim.indices[i + 2]])] = a;
  }
  const shells = new Map();
  for (let v = 0; v < prim.count; v++) {
    const root = find(pointOf[v]);
    if (!shells.has(root)) shells.set(root, []);
    shells.get(root).push(v);
  }
  return [...shells.values()];
}

for (const { id, heightM, expectedShells } of models) {
  const { primitives } = await readGlb(`public/models/${id}.glb`).skinnedPrimitives();
  if (primitives.length !== 1) throw new Error(`${id}: expected one skinned primitive`);
  const prim = primitives[0];
  const names = prim.jointNames.map((name) => name.replace(/^DEF-/, ''));
  const armWeight = (v) => {
    let total = 0;
    for (let k = 0; k < 4; k++) {
      if (isArm(names[prim.joints[v * 4 + k]])) total += prim.weights[v * 4 + k];
    }
    return total;
  };
  const shells = connectedShells(prim).filter((vertices) => {
    if (vertices.length < 200) return false;
    const ys = vertices.map((v) => prim.positions[v * 3 + 1]);
    const meanArm = vertices.reduce((sum, v) => sum + armWeight(v), 0) / vertices.length;
    // The arm and sleeve shells end above -0.1; lower cloth and leg shells
    // extend below it and attach at or below the waist.
    return Math.min(...ys) < -0.1 && Math.max(...ys) < 0.11 && meanArm > 0.05;
  });
  const sizes = shells.map((vertices) => vertices.length).sort((a, b) => b - a);
  if (JSON.stringify(sizes) !== JSON.stringify(expectedShells)) {
    throw new Error(`${id}: lower shells changed: ${sizes}; expected ${expectedShells}`);
  }
  const vertices = shells.flat().sort((a, b) => a - b);
  const meanForeignWeight = vertices.reduce((sum, v) => sum + armWeight(v), 0) / vertices.length;
  const fix = {
    id: `${id}/lower-cloth-follows-legs`, kind: 'arm-drives-lower',
    title: 'Lower cloth follows the waist and legs', confidence: 'high', status: 'applied',
    region: 'lower', foreign: 'armL+armR',
    stats: { vertices: vertices.length, maxDragCm: 0, meanDragCm: 0,
      meanForeignWeight: +meanForeignWeight.toFixed(3), heightBand: [0, heightM * 0.61], donors: 0 },
    removeBones: names.filter(isArm),
    mesh: { node: prim.nodeIndex, mesh: prim.meshIndex, primitive: prim.primIndex, vertexCount: prim.count },
    vertices, donors: {},
  };
  writeFileSync(`public/models/skinfix/${id}.json`, JSON.stringify({
    format: 'mando-skinfix/1', model: id, heightM,
    note: 'Generated by tools/fix-sith-skirts.mjs from the delivered GLB.', fixes: [fix],
  }));
  console.log(`${id}: ${vertices.length} lower-cloth vertices, ${(meanForeignWeight * 100).toFixed(1)}% average arm weight removed`);
}

const indexPath = 'public/models/skinfix/index.json';
const index = JSON.parse(readFileSync(indexPath, 'utf8'));
index.models = [...new Set([...index.models, ...models.map(({ id }) => id)])].sort();
writeFileSync(indexPath, JSON.stringify(index));
